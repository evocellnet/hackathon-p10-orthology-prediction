#!/usr/bin/env python
"""Tables for S4 (docs/S4_trees.md) from results/S4_trees/per_set.tsv -> tables.md, summary.json.
Paired bootstrap over sets (B=2000, seed 11) for Δ(arm − a_nj)."""
import json, os, sys
import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from ancestra.treebench import paired_bootstrap  # noqa: E402

OUT = f"{ROOT}/results/S4_trees"
BASE = "a_nj"
N_CLUSTERS, N_UNITS = 15456, 79782   # results/core_v0_orthobench/e2e_default_manifest.json
ARMS = ["ref", "a_nj", "b_ft", "b_iq", "c_ft3di", "c_iq3di", "d_part", "d_ftcat", "e_fident", "e_fsbits"]
CLASSES = ["mammal", "vert", "vert_invert", "invert"]


def fmt_ci(d, lo, hi):
    return f"{d:+.4f} [{lo:+.4f}, {hi:+.4f}]"


def arm_table(df, truth="m", with_boot=True):
    rows, js = [], {}
    base = df[df.arm == BASE].set_index("set")
    for arm in ARMS:
        x = df[df.arm == arm].set_index("set")
        if x.empty:
            continue
        x = x.loc[base.index.intersection(x.index)]
        b = base.loc[x.index]
        n, ok = x[f"{truth}_all_n"], x[f"{truth}_all_ok"]
        acc = ok.sum() / n.sum()
        tp, fp, fn = x[f"{truth}_tp"].sum(), x[f"{truth}_fp"].sum(), x[f"{truth}_fn"].sum()
        r = dict(arm=arm, sets=len(x), nrf=x.nrf.mean(), qd=x.qd.mean(), acc=acc,
                 orth_P=tp / max(tp + fp, 1), orth_R=tp / max(tp + fn, 1))
        for c in CLASSES:
            nc = x.get(f"{truth}_{c}_n", pd.Series(0, index=x.index)).sum()
            r[f"acc_{c}"] = x.get(f"{truth}_{c}_ok", pd.Series(0, index=x.index)).sum() / nc if nc else np.nan
        if with_boot and arm != BASE:
            r["d_acc"] = paired_bootstrap(b[f"{truth}_all_ok"], b[f"{truth}_all_n"], ok, n)
            vi = f"{truth}_vert_invert"
            if f"{vi}_n" in x and x[f"{vi}_n"].sum() > 0:
                r["d_acc_vert_invert"] = paired_bootstrap(b[f"{vi}_ok"], b[f"{vi}_n"], x[f"{vi}_ok"], x[f"{vi}_n"])
            ones = np.ones(len(x))
            r["d_nrf"] = paired_bootstrap(b.nrf.values, ones, x.nrf.values, ones)
        r["cpu_mean_s"] = x.cpu.mean()
        rows.append(r)
        js[arm] = r
    return rows, js


def cost_fit(df):
    out = {}
    for arm in ARMS[1:]:
        x = df[(df.arm == arm) & df.cpu.notna()]
        if len(x) < 3:
            continue
        A = np.c_[np.ones(len(x)), x.n.values]
        c0, c1 = np.linalg.lstsq(A, x.cpu.values, rcond=None)[0]
        c0 = max(c0, 0.0)
        proj = (N_CLUSTERS * c0 + N_UNITS * c1) / 3600
        # per-cluster CPU at the mean localtree cluster size (79,782 / 15,456 = 5.2 units)
        out[arm] = dict(c0_s=c0, c1_s_per_leaf=c1, cpu_at_5_units_s=c0 + c1 * N_UNITS / N_CLUSTERS,
                        projected_cpu_h_orthobench=proj, acceptable=bool(proj <= 1.0), n_fit=len(x))
    return out


def md_table(rows, keys, heads):
    s = "| " + " | ".join(heads) + " |\n|" + "---|" * len(heads) + "\n"
    for r in rows:
        cells = []
        for k in keys:
            v = r.get(k, "")
            if isinstance(v, tuple):
                cells.append(fmt_ci(*v[:3]))
            elif isinstance(v, float):
                cells.append(f"{v:.4f}" if np.isfinite(v) else "–")
            else:
                cells.append(str(v))
        s += "| " + " | ".join(cells) + " |\n"
    return s


def main():
    df = pd.read_csv(f"{OUT}/per_set.tsv", sep="\t")
    meta = json.load(open(f"{OUT}/run_meta.json"))
    summ, md = {}, ["# S4 tables (generated by scripts/S4_summarize.py; do not edit)\n"]
    # coverage
    m = pd.DataFrame(meta["meta"]).T
    single = m[m.kind == "single"]
    full_n = single[single.scope == "full"].set_index("set").n.astype(int)
    c3_n = single[single.scope == "c3di"].set_index("set").n.astype(int)
    cov = dict(genes_full=int(full_n.sum()), genes_c3di=int(c3_n.sum()),
               frac=float(c3_n.sum() / full_n.sum()), sets_full=int(len(full_n)), sets_c3di=int(len(c3_n)),
               seq_pairs_missing_full=int(single[single.scope == "full"].seq_pairs_missing.astype(int).sum()),
               seq_pairs_full=int(single[single.scope == "full"].n_pairs.astype(int).sum()))
    summ["coverage"] = cov
    md.append(f"**Coverage.** single RefOGs: {cov['genes_c3di']}/{cov['genes_full']} genes with 3Di "
              f"({cov['frac']:.3f}); sets with ≥4 genes: full {cov['sets_full']}, c3di {cov['sets_c3di']}. "
              f"Unscored sequence pairs (−ln S fill = max+1) in full scope: {cov['seq_pairs_missing_full']}/{cov['seq_pairs_full']}.\n")
    keys = ["arm", "sets", "nrf", "d_nrf", "qd", "acc", "d_acc", "orth_P", "orth_R", "acc_vert_invert",
            "d_acc_vert_invert", "acc_mammal", "acc_vert", "acc_invert", "cpu_mean_s"]
    heads = ["arm", "sets", "nRF", "ΔnRF vs a [CI]", "quartet d", "label acc", "Δacc vs a [CI]", "orth P", "orth R",
             "acc vert–invert", "Δacc vert–inv [CI]", "acc mammal", "acc vert", "acc invert", "CPU s/set"]
    for kind, scope, truth, title in [("single", "c3di", "m", "PRIMARY: single RefOGs, c3di scope, matched truth"),
                                      ("single", "c3di", "s5", "single RefOGs, c3di scope, S5 truth"),
                                      ("single", "full", "m", "single RefOGs, full scope, matched truth"),
                                      ("single", "full", "s5", "single RefOGs, full scope, S5 truth"),
                                      ("comp", "c3di", "m", "components (4, descriptive), c3di, matched truth"),
                                      ("comp", "c3di", "s5", "components (4, descriptive), c3di, S5 truth"),
                                      ("comp", "full", "s5", "components (4, descriptive), full, S5 truth")]:
        x = df[(df.kind == kind) & (df.scope == scope)]
        rows, js = arm_table(x, truth, with_boot=True)
        summ[f"{kind}_{scope}_{truth}"] = js
        md.append(f"\n## {title}\n")
        md.append(md_table(rows, keys, heads))
    costs = cost_fit(df[df.arm != "ref"])
    summ["cost"] = costs
    md.append("\n## Cost (CPU = c0 + c1·n fit over all sets; projection to the OrthoBench e2e run: "
              f"{N_CLUSTERS} tree clusters, {N_UNITS} units)\n")
    md.append(md_table([dict(arm=k, **v) for k, v in costs.items()],
                       ["arm", "c0_s", "c1_s_per_leaf", "cpu_at_5_units_s", "projected_cpu_h_orthobench", "acceptable"],
                       ["arm", "c0 s", "c1 s/leaf", "CPU s @5.2 units", "projected CPU-h", "≤1 CPU-h"]))
    # keep rule
    prim = summ["single_c3di_m"]
    verdict = {}
    for arm, r in prim.items():
        if arm in ("ref", BASE):
            continue
        d, lo, hi, _ = r["d_acc"]
        verdict[arm] = dict(d_acc=d, lo=lo, hi=hi, acc_gain=bool(d > 0 and lo > 0),
                            cost_ok=costs.get(arm, {}).get("acceptable", False),
                            replace=bool(d > 0 and lo > 0 and costs.get(arm, {}).get("acceptable", False)))
    summ["keep_rule"] = verdict
    md.append("\n## Keep rule, pre-registered fit-based cost (primary endpoint)\n")
    md.append(md_table([dict(arm=k, **v) for k, v in verdict.items()],
                       ["arm", "d_acc", "lo", "hi", "acc_gain", "cost_ok", "replace"],
                       ["arm", "Δacc", "CI lo", "CI hi", "Δ>0, CI∌0", "cost ok", "replaces a_nj"]))
    # 3Di contrasts (same proteins, same tree method with vs without 3Di), primary scope
    x = df[(df.kind == "single") & (df.scope == "c3di")]
    contr = {}
    rows = []
    for b_arm, x_arm in [("b_iq", "d_part"), ("b_ft", "d_ftcat"), ("b_iq", "c_iq3di"), ("b_ft", "c_ft3di"),
                         ("a_nj", "e_fsbits")]:
        A = x[x.arm == b_arm].set_index("set")
        Bx = x[x.arm == x_arm].set_index("set").loc[A.index]
        r = dict(contrast=f"{x_arm} − {b_arm}")
        for truth in ("m", "s5"):
            r[f"acc_{truth}"] = paired_bootstrap(A[f"{truth}_all_ok"], A[f"{truth}_all_n"], Bx[f"{truth}_all_ok"], Bx[f"{truth}_all_n"])
            r[f"vi_{truth}"] = paired_bootstrap(A[f"{truth}_vert_invert_ok"], A[f"{truth}_vert_invert_n"],
                                                Bx[f"{truth}_vert_invert_ok"], Bx[f"{truth}_vert_invert_n"])
        ones = np.ones(len(A))
        r["nrf"] = paired_bootstrap(A.nrf.values, ones, Bx.nrf.values, ones)
        rows.append(r)
        contr[r["contrast"]] = r
    summ["contrasts_3di"] = contr
    md.append("\n## Does 3Di help? Paired contrasts on identical proteins (single RefOGs, c3di; B=2000, seed 11)\n")
    md.append(md_table(rows, ["contrast", "acc_m", "vi_m", "acc_s5", "vi_s5", "nrf"],
                       ["contrast", "Δacc matched", "Δacc vert–invert matched", "Δacc S5", "Δacc vert–invert S5", "ΔnRF"]))
    cp = f"{OUT}/cost_5units.json"
    if os.path.exists(cp):
        c5 = json.load(open(cp))
        summ["cost_5units"] = c5
        md.append("\n## Cost at localtree cluster size (100 random 5-protein DEV sets; scripts/S4_cost.py)\n")
        md.append(md_table([dict(arm=k, **v) for k, v in c5.items() if not k.startswith("_")],
                           ["arm", "cpu_mean_s", "cpu_median_s", "wall_mean_s", "projected_cpu_h_orthobench", "acceptable"],
                           ["arm", "CPU s mean", "CPU s median", "wall s mean", f"projected CPU-h ({N_CLUSTERS} clusters)", "≤1 CPU-h"]))
        for arm, v in verdict.items():
            v["cost_ok_5units"] = c5.get(arm, {}).get("acceptable", False)
            v["replace"] = bool(v["acc_gain"] and v["cost_ok"] and v["cost_ok_5units"])
        md.append("\n## Keep rule, final (accuracy gain AND both cost criteria)\n")
        md.append(md_table([dict(arm=k, **v) for k, v in verdict.items()],
                           ["arm", "d_acc", "lo", "hi", "acc_gain", "cost_ok", "cost_ok_5units", "replace"],
                           ["arm", "Δacc", "CI lo", "CI hi", "Δ>0, CI∌0", "cost ok (fit)", "cost ok (5 units)", "replaces a_nj"]))
    # per-set primary accuracies
    x = df[(df.kind == "single") & (df.scope == "c3di")].copy()
    x["acc"] = x.m_all_ok / x.m_all_n.replace(0, np.nan)
    piv = x.pivot_table(index="set", columns="arm", values="acc")
    pn = x[x.arm == BASE].set_index("set")[["n", "m_all_n"]]
    piv = pn.join(piv[[a for a in ARMS if a in piv.columns]])
    md.append("\n## Per-RefOG label accuracy (primary scope/truth)\n")
    md.append(piv.round(3).to_markdown())
    json.dump(summ, open(f"{OUT}/summary.json", "w"), indent=1, default=float)
    open(f"{OUT}/tables.md", "w").write("\n".join(md) + "\n")
    print("\n".join(md[:4]))


if __name__ == "__main__":
    main()
