#!/usr/bin/env python
"""L2-plm: markdown tables from results/l2_plm/*.json -> results/l2_plm/tables.md"""
import glob, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from l2_plm_common import RES

GROUPS = ["all", "deep", "shallow", "hard", "hard_deep"]


def fmt(v):
    return f"{v['delta']:+.3f} [{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}]"


def discr_table(f, setname="T_seq"):
    d = json.load(open(f))
    L = [f"#### {os.path.basename(f)} — set {setname}: triplet accuracy (shuffled mean in brackets)", ""]
    g0 = d["groups"]
    hdr = "| arm | " + " | ".join(f"{g} (n={g0[setname + '/' + g]['n']})" for g in GROUPS) + " |"
    L += [hdr, "|---" * (len(GROUPS) + 1) + "|"]
    L.append("| seq | " + " | ".join(f"{g0[setname + '/' + g]['acc']['seq']:.3f}" for g in GROUPS) + " |")
    arms = list(g0[setname + "/all"]["arms"])
    for arm in arms:
        cells = []
        for g in GROUPS:
            r = g0[setname + "/" + g]["arms"][arm]
            cells.append(f"{r['acc']:.3f} ({sum(r['shuf']) / 3:.3f})")
        L.append(f"| {arm} | " + " | ".join(cells) + " |")
    for key, title in (("minus_seq", "Δ(arm − seq)"), ("minus_shuf", "Δ(arm − shuffled mean)")):
        L += ["", f"{title}, paired bootstrap over RefOGs, 95% CI:", "",
              "| arm | " + " | ".join(GROUPS) + " |", "|---" * (len(GROUPS) + 1) + "|"]
        for arm in arms:
            L.append(f"| {arm} | " + " | ".join(fmt(g0[setname + '/' + g]['arms'][arm][key]) for g in GROUPS) + " |")
    con = g0[setname + "/all"].get("contrasts", {})
    if con:
        L += ["", "Paired contrasts (real arms):", "", "| contrast | " + " | ".join(GROUPS) + " |",
              "|---" * (len(GROUPS) + 1) + "|"]
        for c in con:
            L.append(f"| {c} | " + " | ".join(fmt(g0[setname + '/' + g]['contrasts'][c]) for g in GROUPS) + " |")
    L.append("")
    if d.get("pair_auc"):
        L += ["Pooled pair ROC-AUC (all within-RefOG labelled pairs; RefOG bootstrap CI, 200 resamples):", "",
              "| score | all | deep | shallow |", "|---|---|---|---|"]
        keys = sorted({k.split("/", 1)[1] for k in d["pair_auc"]})
        for k in keys:
            L.append(f"| {k} | " + " | ".join(
                f"{d['pair_auc'][g + '/' + k]['auc']:.3f} [{d['pair_auc'][g + '/' + k]['ci95'][0]:.3f}, {d['pair_auc'][g + '/' + k]['ci95'][1]:.3f}]"
                for g in ("all", "deep", "shallow")) + " |")
        L.append("")
    return L


def main():
    L = ["# L2-plm tables (generated by scripts/l2_plm_summarize.py)", ""]
    for f in sorted([os.path.join(RES, "discrimination_final.json")]):
        L += discr_table(f)
    hs = sorted(glob.glob(os.path.join(RES, "head_*.json")))
    if hs:
        L += ["#### Heads (self-derived labels; val = held-out training families)", "",
              "| head | train queries | val triplets | val acc raw cosine | best val acc | best epoch | md5 |",
              "|---|---|---|---|---|---|---|"]
        for f in hs:
            h = json.load(open(f))
            L.append(f"| {h['name']} | {h['n_train_queries']} | {h['n_val_triplets']} | {h['val_acc_raw_cosine']:.4f} | "
                     f"{h['best_val_acc']:.4f} | {h['best_epoch']} | {h['weights_md5']} |")
        L.append("")
    f = os.path.join(RES, "knn_guard.json")
    if os.path.exists(f):
        d = json.load(open(f))
        L += ["#### Idea 4: kNN family guard (S0 completeness, DEV)", "",
              "| variant | mutual cross-family links | τ | accepted | family pairs joined | completeness before → after | new DEV RefOG fusions | RefOG010 fused | largest family |",
              "|---|---|---|---|---|---|---|---|---|"]
        for v in ("real", "shuf11", "shuf23", "shuf47"):
            x = d[v]
            L.append(f"| {v} | {x['n_mutual_cross']} | {x['tau']} | {x['n_accepted']} | {x['n_family_pairs_joined']} | "
                     f"{x['completeness_before']:.3f} → {x['completeness_after']:.3f} | {len(x['new_dev_fusions'])} | "
                     f"{x['refog010_fused']} | {x['largest_family']} |")
        L.append("")
    open(os.path.join(RES, "tables.md"), "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
