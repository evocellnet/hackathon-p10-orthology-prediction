#!/usr/bin/env python
"""Summarise S8 outputs (results/S8_geneloss/*_<species>.tsv) -> tables.md, summary.json, final_calls.tsv."""
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from ancestra.geneloss import MAMMALS  # noqa: E402

R = sys.argv[1] if len(sys.argv) > 1 else "results/S8_geneloss"
WORK = "work/S8"
ORDER = ["A_annotated", "A_otherHOG", "A_gap", "B_annot", "B_pseudo", "B_partial", "C_deleted", "C_relocated",
         "D_undetermined", "D_relocated"]
PSEUDO = ("pseudogene",)


def sp_of(pid: str) -> str:
    for p, s in (("ENSPTRP", "Pan_troglodytes"), ("ENSMUSP", "Mus_musculus"), ("ENSRNOP", "Rattus_norvegicus"),
                 ("ENSCAFP", "Canis_familiaris"), ("ENSMODP", "Monodelphis_domestica"), ("ENSP", "Homo_sapiens")):
        if isinstance(pid, str) and pid.startswith(p):
            return s
    return "?"


def load(kind):
    fs = sorted(glob.glob(os.path.join(R, f"{kind}_*.tsv")))
    return pd.concat([pd.read_csv(f, sep="\t") for f in fs], ignore_index=True) if fs else pd.DataFrame()


def wilson(k, n, z=1.96):
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (round((c - h) / d, 3), round((c + h) / d, 3))


def biotype_cat(b):
    if not isinstance(b, str) or not b:
        return "none"
    top = b.split(";")[0]
    if "pseudogene" in top:
        return "pseudogene"
    if top == "protein_coding":
        return "protein_coding"
    return "other_ncRNA"


def main():
    cand, pos, mask, neg = load("cand"), load("pos"), load("mask"), load("neg")
    gw, known = load("gw"), load("known")
    allc = pd.read_csv(os.path.join(R, "candidates_all.tsv"), sep="\t")
    species = [s for s in MAMMALS if s in set(cand.target)]
    out = {"species_done": species}
    md = ["# S8 tables (generated by scripts/summarize_S8.py)\n"]

    # --- identity threshold for "paralog" hits that look like the ortholog (HOG misassignment)
    pos["qsp"] = pos["query"].map(sp_of)
    thr = {}
    for (t, q), g in pos[pos.recovered].groupby(["target", "qsp"]):
        if len(g) >= 5:
            thr[(t, q)] = float(np.quantile(g.identity, 0.05))
    thr_t = {t: float(np.quantile(g.identity, 0.05)) for t, g in pos[pos.recovered].groupby("target")}
    out["ortholog_identity_p05"] = {f"{t}|{q}": round(v, 3) for (t, q), v in thr.items()}

    def final(r, g):
        c = r.cls
        if c in ("B_pseudo", "B_partial") and r.get("b_on_annot"):
            return "B_annot"
        if c == "C_deleted" and isinstance(r.get("paralog_query"), str):
            th = thr.get((r.target, sp_of(r.paralog_query)), thr_t.get(r.target, 1.0))
            if r.paralog_identity >= th and r.paralog_qcov >= 0.8:
                return "A_otherHOG"
        if c in ("C_deleted", "D_undetermined") and g is not None and bool(g.get("gw_intact", False)) \
                and not bool(g.get("gw_intact_in_locus", False)):
            return "C_relocated" if c == "C_deleted" else "D_relocated"
        return c

    # retrocopy guard for genome-wide hits (same rule as at the locus): an intronless
    # intact hit does not count as a relocated copy of a multi-exon HOG
    import pickle
    hi = pickle.load(open(os.path.join(WORK, "hogindex.pkl"), "rb"))
    nex = {}
    for sp in MAMMALS:
        nex.update(pd.read_parquet(os.path.join(WORK, f"cds_{sp}.parquet")).groupby("protein_id").size().to_dict())
    if len(gw):
        med = [float(np.median([nex.get(x, 1) for x in hi.members[h] if hi.species_of[x] != t] or [1]))
               for h, t in zip(gw.hog, gw.target)]
        gw["multi_exon_hog"] = np.array(med) >= 2
        retro = gw.gw_intact.fillna(False).astype(bool) & gw.multi_exon_hog & (gw.gw_intact_n_introns.fillna(0) == 0)
        gw["gw_intact_retro"] = retro
        gw.loc[retro, "gw_intact"] = False
    gwi = {(r.target, r.hog): r for r in gw.itertuples()} if len(gw) else {}
    from ancestra.geneloss import CdsIndex
    cdsx = {sp: CdsIndex.from_parquet(os.path.join(WORK, f"cds_{sp}.parquet")) for sp in species}

    def on_annotated_cds(r):
        """B_* best hit lying on an annotated target protein (this HOG or a target-only HOG):
        the annotation models a coding gene where the alignment shows frameshifts/stops
        (assembly indel or a pseudogene modelled as coding) -> unresolved, not a confirmed loss."""
        if r.get("cls") not in ("B_pseudo", "B_partial") or not isinstance(r.get("hit_blocks"), str):
            return ""
        bl = [tuple(int(v) for v in x.split("-")) for x in r["hit_blocks"].split(",")]
        tot = sum(e - s0 + 1 for s0, e in bl) or 1
        for g, bp in cdsx[r["target"]].overlap(str(r["contig"]), bl).items():
            if bp < 0.2 * tot:
                continue
            j = hi.hog_of.get(g)
            if j == r["hog"] or {hi.species_of[x] for x in hi.members[j]} <= {r["target"]}:
                return g
        return ""

    for df_ in (cand, pos):
        df_["contig"] = df_["contig"].astype(str)
        df_["b_on_annot"] = [on_annotated_cds(r) for r in df_.to_dict("records")]
    fin = []
    for r in cand.to_dict("records"):
        g = gwi.get((r["target"], r["hog"]))
        rr = pd.Series(r)
        fin.append(final(rr, g._asdict() if g is not None else None))
    cand["final_cls"] = fin
    if len(gw):
        cand = cand.merge(gw.drop(columns=["locus_cls"]), on=["hog", "target"], how="left")
    cand["biotype_cat"] = cand.gff_biotypes.map(biotype_cat)
    # readable HOG name: gene symbol of the human (else mouse, dog, rat) member
    names = {}
    for sp in ["Homo_sapiens", "Mus_musculus", "Canis_familiaris", "Rattus_norvegicus"]:
        tb = pd.read_parquet(f"data/genomes/orthobench/{sp}.parquet", columns=["protein_id", "gene_id"])
        gf = pd.read_parquet(os.path.join(WORK, f"gff_genes_{sp}.parquet"), columns=["gene_id", "name"])
        names[sp] = dict(tb.merge(gf, on="gene_id").set_index("protein_id")["name"])

    def hog_name(h):
        for sp in names:
            for g in hi.in_species(int(h), sp):
                if names[sp].get(g):
                    return names[sp][g]
        return ""
    cand["hog_name"] = cand.hog.map(hog_name)
    cand.to_csv(os.path.join(R, "final_calls.tsv"), sep="\t", index=False)

    # --- table 1: candidates and classes per species
    md.append("## 1. Apparent losses (Theria HOGs present in 5 of 6 mammals) by final class\n")
    tab = pd.crosstab(cand.target, cand.final_cls).reindex(columns=[c for c in ORDER if c in set(cand.final_cls)],
                                                            fill_value=0)
    tab = tab.reindex([s for s in MAMMALS if s in tab.index])
    tab["n"] = tab.sum(axis=1)
    tab.loc["all"] = tab.sum()
    md.append(tab.to_markdown() + "\n")
    out["final_counts"] = {k: {kk: int(vv) for kk, vv in v.items()} for k, v in tab.T.to_dict().items()}
    raw = pd.crosstab(cand.target, cand.cls)
    raw.loc["all"] = raw.sum()
    md.append("Raw locus classes (before the genome-wide and paralog-identity post-rules):\n")
    md.append(raw.to_markdown() + "\n")
    md.append(f"Candidates per target before locus search (`candidates_all.tsv`): "
              f"{allc.target.value_counts().to_dict()}\n")
    lk = pd.crosstab(cand.target, cand.locus_kind)
    md.append("Locus kinds:\n\n" + lk.to_markdown() + "\n")
    conf = cand.groupby("target").conflict.apply(lambda x: int(x.astype('boolean').fillna(False).astype(bool).sum()))
    md.append(f"B_pseudo called by the majority rule over a single intact query (conflict): {conf.to_dict()}\n")

    # --- table 2: controls
    md.append("## 2. Controls\n")
    rows = []
    for t in species:
        p = pos[pos.target == t]
        m = mask[mask.target == t]
        n_ = neg[neg.target == t]
        k = int(p.recovered.sum())
        kg = int(p.recovered_gap_rule.sum())
        has_locus = p.locus_kind.isin(["bracketed", "one_sided"])
        mA = m.cls.isin(["A_annotated", "A_gap"])
        nA = n_.cls.isin(["A_annotated", "A_gap"])
        pl = p.cls.isin(["B_pseudo", "C_deleted"]) & p.b_on_annot.eq("")
        rows.append({"target": t, "pos_n": len(p), "pos_recovered": k, "sens": round(k / max(len(p), 1), 3),
                     "sens_CI95": wilson(k, len(p)), "sens_gap_rule": round(kg / max(len(p), 1), 3),
                     "pos_with_locus": int(has_locus.sum()),
                     "pos_called_loss(B/C)": int(pl.sum()),
                     "pos_B_annot": int((p.cls.isin(["B_pseudo", "B_partial"]) & p.b_on_annot.ne("")).sum()),
                     "mask_n": len(m), "mask_intact_FP": int(mA.sum()),
                     "neg_n": len(n_), "neg_intact_FP": int(nA.sum()),
                     "neg_any_hit_qcov>=0.3": int((n_.qcov.fillna(0) >= 0.3).sum()),
                     "neg_B": int(n_.cls.isin(["B_pseudo", "B_partial"]).sum()),
                     "mask_B": int(m.cls.isin(["B_pseudo", "B_partial"]).sum())})
    ct = pd.DataFrame(rows).set_index("target")
    tot = ct.drop(columns=["sens", "sens_CI95", "sens_gap_rule"]).sum()
    md.append(ct.to_markdown() + "\n")
    K, N = int(tot.pos_recovered), int(tot.pos_n)
    pooled = {"pos_n": N, "pos_recovered": K, "sens": round(K / max(N, 1), 3), "sens_CI95": wilson(K, N),
              "sens_gap_rule": round(int(pos.recovered_gap_rule.sum()) / max(N, 1), 3),
              "pos_called_loss": int(tot["pos_called_loss(B/C)"]),
              "false_loss_rate": round(int(tot["pos_called_loss(B/C)"]) / max(N, 1), 4),
              "false_loss_CI95": wilson(int(tot["pos_called_loss(B/C)"]), N),
              "mask_n": int(tot.mask_n), "mask_intact_FP": int(tot.mask_intact_FP),
              "mask_FP_CI95": wilson(int(tot.mask_intact_FP), int(tot.mask_n)),
              "neg_n": int(tot.neg_n), "neg_intact_FP": int(tot.neg_intact_FP),
              "neg_FP_CI95": wilson(int(tot.neg_intact_FP), int(tot.neg_n))}
    out["controls"] = {"per_species": json.loads(ct.to_json(orient="index")), "pooled": pooled}
    md.append(f"Pooled: {pooled}\n")
    fails = pos[~pos.recovered]
    md.append("Positive controls not recovered, by class: " + str(fails.cls.value_counts().to_dict()) + "\n")

    # --- precision estimates (per species; the relevant false-loss rate for *unannotated* loci counts
    # positives whose hidden gene aligned with frameshifts/stops (B on the hidden CDS) as false losses, since
    # without the annotation they would be called B_pseudo)
    fp_int = (pooled["mask_intact_FP"] + pooled["neg_intact_FP"]) / max(pooled["mask_n"] + pooled["neg_n"], 1)
    prow = []
    for t in species + ["all"]:
        d = cand if t == "all" else cand[cand.target == t]
        cc = ct.sum() if t == "all" else ct.loc[t]
        f_loss = (cc["pos_called_loss(B/C)"] + cc["pos_B_annot"]) / max(cc.pos_n, 1)
        sens = cc.pos_recovered / max(cc.pos_n, 1)
        loss = int(d.final_cls.isin(["B_pseudo", "C_deleted"]).sum())
        pres = int(d.final_cls.isin(["A_annotated", "A_gap", "A_otherHOG"]).sum())
        efl = pres / max(sens, 1e-9) * f_loss
        efp = loss * fp_int
        prow.append({"target": t, "loss_calls": loss, "present_calls": pres, "P(loss|present)": round(f_loss, 3),
                     "exp_false_loss": round(efl, 1), "precision_loss": round(1 - efl / max(loss, 1), 3),
                     "P(intact|absent)": round(fp_int, 4), "exp_false_present": round(efp, 1),
                     "precision_present": round(1 - efp / max(pres, 1), 3)})
    pt = pd.DataFrame(prow).set_index("target")
    # pooled row: sum the per-species expectations (rates differ a lot by assembly)
    sp_rows = pt.drop(index="all")
    pt.loc["all", "exp_false_loss"] = round(sp_rows.exp_false_loss.sum(), 1)
    pt.loc["all", "precision_loss"] = round(1 - sp_rows.exp_false_loss.sum() / max(pt.loc["all", "loss_calls"], 1), 3)
    out["precision_estimates"] = json.loads(pt.to_json(orient="index"))
    md.append("## 3. Precision estimates (from the controls)\n")
    md.append("Expected false loss calls = (present calls / sensitivity) x P(loss|present); P(loss|present) = "
              "fraction of positives called B (any, incl. on the hidden CDS) or C. Expected false present calls = "
              "loss calls x P(intact|absent) (masked + random windows, pooled).\n")
    md.append(pt.to_markdown() + "\n")

    # --- table 3: Ensembl/GENCODE biotype at the best hit (independent annotation check)
    md.append("## 4. Ensembl biotype at the best hit (independent check; human/mouse have GENCODE pseudogene "
              "annotation)\n")
    bt = pd.crosstab([cand.target, cand.final_cls], cand.biotype_cat)
    md.append(bt.to_markdown() + "\n")
    hm = cand[cand.target.isin(["Homo_sapiens", "Mus_musculus"])]
    agree = {}
    for c in ("B_pseudo", "A_gap", "B_partial"):
        x = hm[hm.final_cls == c]
        agree[c] = {"n": len(x), "pseudogene": int((x.biotype_cat == "pseudogene").sum()),
                    "protein_coding": int((x.biotype_cat == "protein_coding").sum()),
                    "none": int((x.biotype_cat == "none").sum())}
    out["gencode_check_human_mouse"] = agree
    md.append(f"Human+mouse: {agree}\n")
    # reverse view: candidate loci where Ensembl itself annotates a pseudogene -> our class
    psg = hm[hm.biotype_cat == "pseudogene"]
    md.append("Human+mouse loci whose best hit overlaps an Ensembl pseudogene, by our class: "
              f"{psg.final_cls.value_counts().to_dict()}\n")

    # --- genome-wide
    if len(gw):
        md.append("## 5. Genome-wide miniprot (B/C/D candidates)\n")
        g = gw.copy()
        g["intact_elsewhere"] = g.gw_intact.fillna(False).astype(bool) & ~g.get("gw_intact_in_locus", False).fillna(False).astype(bool)
        g["retrocopy_only"] = g.gw_intact_retro
        g["intact_elsewhere_annotated"] = g.intact_elsewhere & g.get("gw_intact_annotated", "").fillna("").astype(str).ne("")
        g["intact_elsewhere_intronless"] = g.intact_elsewhere & (g.get("gw_intact_n_introns", 0).fillna(0) == 0)
        s = g.groupby(["target", "locus_cls"]).agg(n=("hog", "size"), intact_elsewhere=("intact_elsewhere", "sum"),
                                                     annotated=("intact_elsewhere_annotated", "sum"),
                                                     intronless=("intact_elsewhere_intronless", "sum"),
                                                     retrocopy_excluded=("retrocopy_only", "sum"))
        md.append(s.to_markdown() + "\n")

    # --- known biology
    if len(known):
        md.append("## 6. Known losses (direct test, mouse-protein HOG vs hominid genome)\n")
        cols = [c for c in ["gene", "target", "cls", "locus_kind", "contig", "hit_start", "hit_end", "query", "qcov",
                            "identity", "fs", "st", "nq_intact", "nq_disrupted", "gff_names", "gff_biotypes",
                            "hog_species", "in_candidates"] if c in known]
        md.append(known[cols].to_markdown(index=False) + "\n")
        out["known"] = known[cols].to_dict("records")

    # --- examples
    md.append("## 7. Examples\n")
    ex_cols = [c for c in ["target", "hog", "hog_name", "final_cls", "contig", "hit_start", "query", "qcov", "identity", "fs", "st",
                           "nq_intact", "nq_disrupted", "n_paralog_hits", "overlap_gene", "paralog_gene", "paralog_identity",
                           "gff_names", "gff_biotypes"]
               if c in cand]
    for c in ORDER:
        x = cand[cand.final_cls == c]
        if len(x):
            x = x.sort_values(["target", "hog"])
            pick = x[x.gff_names.fillna("").ne("")].head(4)
            pick = pd.concat([pick, x.head(6 - len(pick))]).drop_duplicates(["target", "hog"]).head(6)
            md.append(f"**{c}** (n={len(x)})\n\n" + pick[ex_cols].to_markdown(index=False) + "\n")

    # --- corrected presence/absence
    present = cand.final_cls.isin(["A_annotated", "A_gap", "A_otherHOG", "C_relocated", "D_relocated"])
    lost = cand.final_cls.isin(["B_pseudo", "C_deleted"])
    corr = cand.groupby("target").apply(lambda d: pd.Series({
        "apparent_losses": len(d),
        "present_after_DNA": int(d.final_cls.isin(["A_annotated", "A_gap", "A_otherHOG", "C_relocated", "D_relocated"]).sum()),
        "confirmed_loss": int(d.final_cls.isin(["B_pseudo", "C_deleted"]).sum()),
        "unresolved": int(d.final_cls.isin(["B_annot", "B_partial", "D_undetermined"]).sum())}), include_groups=False)
    corr.loc["all"] = corr.sum()
    corr["frac_not_loss"] = (corr.present_after_DNA / corr.apparent_losses).round(3)
    md.append("## 8. HOG presence/absence after DNA validation\n")
    md.append(corr.to_markdown() + "\n")
    out["presence_correction"] = json.loads(corr.to_json(orient="index"))
    out["n_present"] = int(present.sum())
    out["n_lost"] = int(lost.sum())

    open(os.path.join(R, "tables.md"), "w").write("\n".join(md))
    json.dump(out, open(os.path.join(R, "summary.json"), "w"), indent=1, default=str)
    print("\n".join(md))


if __name__ == "__main__":
    main()
